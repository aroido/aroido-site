function renderTagList(post) {
  if (!post.tagsWithSlugs.length) {
    return "";
  }

  return `<ul class="tag-list" aria-label="Post tags">${post.tagsWithSlugs
    .map((tag) => `<li>${escapeHtml(tag.label)}</li>`)
    .join("")}</ul>`;
}

function formatPostCountLabel(count) {
  return `${count} ${count === 1 ? "post" : "posts"} on this page`;
}

