              <ul class="article-recent-list">
                ${recentPosts
                  .map(
                    (recentPost) => `
                      <li>
                        <a href="${recentPost.path}">${escapeHtml(recentPost.title)}</a>
                        <span>${escapeHtml(recentPost.displayDate)}</span>
                      </li>`
                  )
                  .join("")}
              </ul>
